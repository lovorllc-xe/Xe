#!/usr/bin/env python3
"""Renders logo/png/XeLogo.jpg as colored (24-bit ANSI) ASCII art made of characters.

Writes logo/ascii/xe.ans and compiler/logo.xe (the copy `xe --version` prints).
Requires Pillow. Usage: scripts/make-logo.py [columns]
"""
import os, sys
from PIL import Image

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
cols = int(sys.argv[1]) if len(sys.argv) > 1 else 64
img = Image.open(os.path.join(root, "logo/png/XeLogo.jpg")).convert("RGB")

box = Image.eval(img.convert("L"), lambda v: 255 if v < 200 else 0).getbbox()
img = img.crop(box)
w = cols
h = max(1, round(img.height * w / img.width * 0.5))   # characters are about twice as tall as wide
big = img.resize((w * 4, h * 4), Image.LANCZOS)         # sample 4x4 pixels per character
px = big.load()
RAMP = ".:-=+*#"

LIGHT, DARK = (38, 132, 162), (20, 98, 132)   # the two teal tones of the logo
def q(c): return LIGHT if (0.299 * c[0] + 0.587 * c[1] + 0.114 * c[2]) > 103 else DARK
rows = []
for y in range(h):
    out, last = "", None
    for x in range(w):
        total, r, g, b = 0.0, 0, 0, 0
        for dy in range(4):
            for dx in range(4):
                pr, pg, pb = px[x * 4 + dx, y * 4 + dy]
                d = 1.0 - (0.299 * pr + 0.587 * pg + 0.114 * pb) / 255.0
                if d > 0.05:
                    total += d; r += pr * d; g += pg * d; b += pb * d
        cover = total / 16.0
        if cover < 0.12:
            cell, style = " ", None
        else:
            idx = min(len(RAMP) - 1, int(cover * 1.15 * len(RAMP)))
            cell = RAMP[max(idx, 2)] if cover > 0.45 else RAMP[idx]
            style = q((int(r / total), int(g / total), int(b / total)))
        if style != last:
            out += "\x1b[0m" if style is None else "\x1b[1;38;2;%d;%d;%dm" % style
            last = style
        out += cell
    rows.append(out + "\x1b[0m")

os.makedirs(os.path.join(root, "logo/ascii"), exist_ok=True)
with open(os.path.join(root, "logo/ascii/xe.ans"), "w") as f:
    f.write("\n".join(rows) + "\n")

# Xe has no \x escape, so the module stores ESC as a backtick and restores it.
with open(os.path.join(root, "compiler/logo.xe"), "w") as f:
    f.write("module logo\nbegin\n    // Generated by scripts/make-logo.py - do not edit.\n")
    f.write("    fn restore(text: string): string\n    begin\n        var result: string := str.builder(\"\")\n")
    f.write("        var index: int := 0\n        while index < str.length(text) {\n")
    f.write("            var value: int := str.char(text, index)\n")
    f.write("            if value = 96 { result := str.append(result, str.fromchar(27)) }\n")
    f.write("            else { result := str.append(result, str.fromchar(value)) }\n")
    f.write("            index := index + 1\n        }\n        return result\n    end\n\n")
    f.write("    fn art(): string\n    begin\n        var text: string := str.builder(\"\")\n")
    for r in rows:
        f.write('        text := str.append(text, "%s\\n")\n' % r.replace("\x1b", "`"))
    f.write("        return restore(text)\n    end\nend\n")
print("logo: %d columns x %d rows" % (w, h))
